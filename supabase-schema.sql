-- ========================================================
-- SMA LABSCHOOL UNESA 1 - SUPABASE DATABASE SCHEMA
-- Execute this script in your Supabase SQL Editor
-- ========================================================

-- 1. Create FAQs Table
CREATE TABLE IF NOT EXISTS public.smal_faqs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question TEXT NOT NULL,
  answer TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Create News / Updates Table
CREATE TABLE IF NOT EXISTS public.smal_updates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  caption TEXT,
  hashtags TEXT,
  published_at TEXT,
  image_url TEXT,
  image_alt TEXT,
  is_spotlight BOOLEAN DEFAULT false,
  post_type TEXT DEFAULT 'forever', -- 'forever' (Berita Selamanya) or 'deadline' (Berita Batas Waktu)
  deadline_at TIMESTAMP WITH TIME ZONE, -- Expiration date/time (NULL for forever posts)
  media_type TEXT DEFAULT 'image', -- 'image', 'video', 'instagram', 'youtube'
  video_url TEXT, -- Direct video URL or YouTube/Drive video link
  instagram_url TEXT, -- Instagram post / reel URL to repost
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Create Inquiries / Contact Form Table
CREATE TABLE IF NOT EXISTS public.smal_inquiries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  message TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Create 5 Featured Programs (Pilar Program Unggulan) Table
CREATE TABLE IF NOT EXISTS public.smal_programs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT UNIQUE NOT NULL, -- 'sks', 'bahasa', 'digital', 'international', 'preuni'
  title TEXT NOT NULL,
  badge_text TEXT,
  description TEXT,
  full_content TEXT,
  image_url TEXT,
  moments JSONB DEFAULT '[]'::jsonb, -- Array of { url, caption }
  circle_bg TEXT DEFAULT 'bg-[#002B66]',
  order_index INT DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. Create Faculty / Teachers Table
CREATE TABLE IF NOT EXISTS public.smal_faculty (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  role TEXT NOT NULL,
  subject TEXT,
  image_url TEXT,
  education_history TEXT, -- e.g. S1 Pendidikan Biologi UNESA, S2 Magister Sains ITB
  bio TEXT,
  moments JSONB DEFAULT '[]'::jsonb,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 6. Create Student Activity Reports Table
CREATE TABLE IF NOT EXISTS public.smal_activities (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  tag TEXT,
  event_date TEXT,
  description TEXT,
  full_content TEXT,
  image_url TEXT,
  moments JSONB DEFAULT '[]'::jsonb,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 7. Create Extracurriculars Table
CREATE TABLE IF NOT EXISTS public.smal_extracurriculars (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT,
  description TEXT,
  full_content TEXT,
  schedule TEXT DEFAULT 'Setiap Sabtu / Sepulang Sekolah',
  image_url TEXT,
  moments JSONB DEFAULT '[]'::jsonb,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 8. Create General Settings Table
CREATE TABLE IF NOT EXISTS public.smal_settings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key TEXT UNIQUE NOT NULL,
  value TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);


ALTER TABLE public.smal_activities ADD COLUMN IF NOT EXISTS full_content TEXT;
ALTER TABLE public.smal_activities ADD COLUMN IF NOT EXISTS moments JSONB DEFAULT '[]'::jsonb;

ALTER TABLE public.smal_extracurriculars ADD COLUMN IF NOT EXISTS full_content TEXT;
ALTER TABLE public.smal_extracurriculars ADD COLUMN IF NOT EXISTS schedule TEXT DEFAULT 'Setiap Sabtu / Sepulang Sekolah';
ALTER TABLE public.smal_extracurriculars ADD COLUMN IF NOT EXISTS moments JSONB DEFAULT '[]'::jsonb;

